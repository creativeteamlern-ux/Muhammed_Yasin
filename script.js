// DETAIL PAGES — BROWSER BACK / FORWARD SUPPORT
// ----------------------------------------------------

const overlay = document.querySelector('#detail-overlay');
const detailBody = document.querySelector('#detail-body');
const closeButton = document.querySelector('#detail-close');

const detailKeys = new Set(Object.keys(content));
const detailPrefix = '#';

function detailFromLocation() {
  const key = decodeURIComponent(window.location.hash.slice(1));
  return detailKeys.has(key) ? key : null;
}

function renderDetail(key) {
  if (!overlay || !detailBody || !closeButton) return;

  if (key && content[key]) {
    detailBody.innerHTML = content[key];
    overlay.hidden = false;
    document.body.style.overflow = 'hidden';

    // Reset detail scroll when opening a different page.
    const scrollContainer = overlay.querySelector('.detail-dialog');
    if (scrollContainer) scrollContainer.scrollTop = 0;

    closeButton.focus({ preventScroll: true });
  } else {
    overlay.hidden = true;
    document.body.style.overflow = '';
  }
}

function syncDetailWithLocation() {
  renderDetail(detailFromLocation());
}

// Open a detail page and create a browser history entry.
function openDetail(key) {
  if (!detailKeys.has(key)) return;

  if (detailFromLocation() === key) {
    renderDetail(key);
    return;
  }

  const url = new URL(window.location.href);
  url.hash = key;

  window.history.pushState(
    { portfolioDetail: key },
    '',
    url
  );

  renderDetail(key);
}

// Close the detail page.
// If opened from the portfolio, Back returns to the previous state.
function closeDetail() {
  if (!overlay || overlay.hidden) return;

  if (window.history.state?.portfolioDetail) {
    window.history.back();
  } else {
    const url = new URL(window.location.href);
    url.hash = 'about';

    window.history.replaceState(null, '', url);
    renderDetail(null);
  }
}

// Clicking an About Me shortcut opens its detail page.
document.querySelectorAll('[data-open]').forEach(link => {
  link.addEventListener('click', event => {
    event.preventDefault();
    openDetail(link.dataset.open);
  });
});

// Close button.
if (closeButton) {
  closeButton.addEventListener('click', closeDetail);
}

// Clicking outside the detail dialog closes it.
if (overlay) {
  overlay.addEventListener('click', event => {
    if (event.target === overlay) {
      closeDetail();
    }
  });
}

// Escape key closes the detail page.
document.addEventListener('keydown', event => {
  if (event.key === 'Escape' && overlay && !overlay.hidden) {
    closeDetail();
  }
});

// Native browser Back and Forward navigation.
window.addEventListener('popstate', syncDetailWithLocation);
window.addEventListener('hashchange', syncDetailWithLocation);

// Support direct links and page refreshes, e.g. #technical-stack.
syncDetailWithLocation();

