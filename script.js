document.querySelectorAll('.project-expand').forEach(button => {
  button.addEventListener('click', () => {
    const extra = button.nextElementSibling;
    if (!extra) return;

    extra.hidden = !extra.hidden;

    button.setAttribute('aria-expanded', String(!extra.hidden));
    button.textContent = extra.hidden ? 'Explore ↗' : 'Close ↑';
  });
});

// Activate project expansion when artwork is tapped.
document.querySelectorAll('.projects .project-card > img').forEach(img => {
  img.tabIndex = 0;
  img.setAttribute('role', 'button');
  img.setAttribute('aria-label', 'Explore ' + (img.alt || 'project'));

  const activate = () => {
    img.closest('.project-card')
      ?.querySelector('.project-expand')
      ?.click();
  };

  img.addEventListener('click', activate);

  img.addEventListener('keydown', event => {
    if (event.key === 'Enter' || event.key === ' ') {
      event.preventDefault();
      activate();
    }
  });
});

// Dark-theme artwork interactions.
document.querySelectorAll('.projects .project-card').forEach(card => {
  card.addEventListener('click', event => {
    if (document.documentElement.dataset.theme !== 'dark') return;
    if (event.target.closest('button, a')) return;

    const rect = card.getBoundingClientRect();
    const x = event.clientX - rect.left;

    if (x < rect.width * (window.innerWidth <= 700 ? 1 : 0.5)) {
      card.querySelector('.project-expand')?.click();
    }
  });
});

